// ============================================================
// AXI4 主机接口
// 发起突发读/写事务，用于DMA数据搬运
// 将DMA引擎的简单读写请求转换为AXI4协议事务
// ============================================================
module AXI4主机接口 #(
    parameter 地址位宽     = 64,
    parameter 数据位宽     = 128,
    parameter ID位宽       = 4,
    parameter 写选通位宽   = 数据位宽 / 8
)(
    input  logic                    时钟,
    input  logic                    复位_低有效,

    // --- AXI4 主机接口 ---
    // 写地址通道
    output logic [ID位宽-1:0]       主机_写地址ID,
    output logic [地址位宽-1:0]     主机_写地址,
    output logic [7:0]              主机_写突发长度,     // 突发传输节拍数-1
    output logic [2:0]              主机_写突发大小,     // 每拍字节数的log2
    output logic [1:0]              主机_写突发类型,     // 00=固定, 01=递增, 10=回绕
    output logic                    主机_写地址有效,
    input  logic                    主机_写地址就绪,

    // 写数据通道
    output logic [数据位宽-1:0]     主机_写数据,
    output logic [写选通位宽-1:0]   主机_写选通,
    output logic                    主机_写最后一拍,     // 突发传输最后一拍标记
    output logic                    主机_写数据有效,
    input  logic                    主机_写数据就绪,

    // 写响应通道
    input  logic [ID位宽-1:0]       主机_写响应ID,
    input  logic [1:0]              主机_写响应,
    input  logic                    主机_写响应有效,
    output logic                    主机_写响应就绪,

    // 读地址通道
    output logic [ID位宽-1:0]       主机_读地址ID,
    output logic [地址位宽-1:0]     主机_读地址,
    output logic [7:0]              主机_读突发长度,
    output logic [2:0]              主机_读突发大小,
    output logic [1:0]              主机_读突发类型,
    output logic                    主机_读地址有效,
    input  logic                    主机_读地址就绪,

    // 读数据通道
    input  logic [ID位宽-1:0]       主机_读数据ID,
    input  logic [数据位宽-1:0]     主机_读数据,
    input  logic [1:0]              主机_读响应,
    input  logic                    主机_读最后一拍,
    input  logic                    主机_读数据有效,
    output logic                    主机_读数据就绪,

    // --- DMA引擎接口 ---
    // 读请求
    input  logic                    读请求,
    input  logic [地址位宽-1:0]     读地址,
    input  logic [15:0]             读长度_字节,
    output logic                    读完成,

    // 读数据输出
    output logic [数据位宽-1:0]     读出数据,
    output logic                    读出数据有效,

    // 写请求
    input  logic                    写请求,
    input  logic [地址位宽-1:0]     写地址,
    input  logic [15:0]             写长度_字节,
    output logic                    写完成,

    // 写数据输入
    input  logic [数据位宽-1:0]     写入数据,
    input  logic                    写入数据有效,
    output logic                    写入数据就绪
);

    localparam 每拍字节数 = 数据位宽 / 8;       // 128/8 = 16字节
    localparam 大小编码   = $clog2(每拍字节数);  // log2(16) = 4

    // 固定赋值
    assign 主机_写地址ID   = '0;
    assign 主机_写突发大小 = 大小编码[2:0];
    assign 主机_写突发类型 = 2'b01;    // 递增突发（INCR）
    assign 主机_读地址ID   = '0;
    assign 主机_读突发大小 = 大小编码[2:0];
    assign 主机_读突发类型 = 2'b01;    // 递增突发（INCR）
    assign 主机_写选通     = {写选通位宽{1'b1}};  // 全选通（所有字节有效）
    assign 主机_写响应就绪 = 1'b1;     // 始终接受写响应

    // ===== 读通道状态机 =====
    typedef enum logic [1:0] {
        读_空闲,       // 等待读请求
        读_发地址,     // 发送读地址到AXI总线
        读_接收数据,   // 接收AXI读数据
        读_完成        // 读事务完成
    } 读状态类型;

    读状态类型 读状态;
    logic [15:0] 读总节拍数;    // 本次读事务的总节拍数
    logic [15:0] 读节拍计数;    // 已接收的节拍数

    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            读状态         <= 读_空闲;
            主机_读地址有效 <= 1'b0;
            主机_读地址     <= '0;
            主机_读突发长度 <= '0;
            主机_读数据就绪 <= 1'b0;
            读完成         <= 1'b0;
            读出数据有效   <= 1'b0;
            读总节拍数     <= '0;
            读节拍计数     <= '0;
        end else begin
            读完成       <= 1'b0;
            读出数据有效 <= 1'b0;

            case (读状态)
                // ---- 空闲：等待DMA发起读请求 ----
                读_空闲: begin
                    if (读请求) begin
                        // 计算需要多少个节拍
                        读总节拍数     <= (读长度_字节 + 每拍字节数 - 1) / 每拍字节数;
                        主机_读地址     <= 读地址;
                        主机_读突发长度 <= ((读长度_字节 + 每拍字节数 - 1) / 每拍字节数) - 1;
                        主机_读地址有效 <= 1'b1;
                        读节拍计数     <= '0;
                        读状态         <= 读_发地址;
                    end
                end

                // ---- 发地址：等待从机接受读地址 ----
                读_发地址: begin
                    if (主机_读地址就绪) begin
                        主机_读地址有效 <= 1'b0;
                        主机_读数据就绪 <= 1'b1;   // 准备好接收数据
                        读状态         <= 读_接收数据;
                    end
                end

                // ---- 接收数据：逐拍接收读数据 ----
                读_接收数据: begin
                    if (主机_读数据有效 && 主机_读数据就绪) begin
                        读出数据     <= 主机_读数据;
                        读出数据有效 <= 1'b1;
                        读节拍计数   <= 读节拍计数 + 1;
                        if (主机_读最后一拍) begin
                            // 收到最后一拍，结束接收
                            主机_读数据就绪 <= 1'b0;
                            读状态         <= 读_完成;
                        end
                    end
                end

                // ---- 完成：通知DMA引擎读事务完成 ----
                读_完成: begin
                    读完成 <= 1'b1;
                    读状态 <= 读_空闲;
                end
            endcase
        end
    end

    // ===== 写通道状态机 =====
    typedef enum logic [1:0] {
        写_空闲,       // 等待写请求
        写_发地址,     // 发送写地址到AXI总线
        写_发送数据,   // 逐拍发送写数据
        写_完成        // 等待写响应，完成写事务
    } 写状态类型;

    写状态类型 写状态;
    logic [15:0] 写总节拍数;
    logic [15:0] 写节拍计数;

    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            写状态         <= 写_空闲;
            主机_写地址有效 <= 1'b0;
            主机_写地址     <= '0;
            主机_写突发长度 <= '0;
            主机_写数据有效 <= 1'b0;
            主机_写最后一拍 <= 1'b0;
            主机_写数据     <= '0;
            写完成         <= 1'b0;
            写入数据就绪   <= 1'b0;
            写总节拍数     <= '0;
            写节拍计数     <= '0;
        end else begin
            写完成 <= 1'b0;

            case (写状态)
                // ---- 空闲：等待DMA发起写请求 ----
                写_空闲: begin
                    if (写请求) begin
                        写总节拍数     <= (写长度_字节 + 每拍字节数 - 1) / 每拍字节数;
                        主机_写地址     <= 写地址;
                        主机_写突发长度 <= ((写长度_字节 + 每拍字节数 - 1) / 每拍字节数) - 1;
                        主机_写地址有效 <= 1'b1;
                        写节拍计数     <= '0;
                        写状态         <= 写_发地址;
                    end
                end

                // ---- 发地址：等待从机接受写地址 ----
                写_发地址: begin
                    if (主机_写地址就绪) begin
                        主机_写地址有效 <= 1'b0;
                        写入数据就绪   <= 1'b1;    // 通知DMA可以发数据了
                        写状态         <= 写_发送数据;
                    end
                end

                // ---- 发送数据：直通模式，DMA数据→AXI写数据 ----
                写_发送数据: begin
                    主机_写数据     <= 写入数据;
                    主机_写数据有效 <= 写入数据有效;
                    if (写入数据有效) begin
                        写节拍计数     <= 写节拍计数 + 1;
                        // 最后一拍时拉高wlast
                        主机_写最后一拍 <= (写节拍计数 == 写总节拍数 - 1);
                    end
                    // 发送完最后一拍后结束
                    if (主机_写数据有效 && 主机_写数据就绪 && 主机_写最后一拍) begin
                        主机_写数据有效 <= 1'b0;
                        主机_写最后一拍 <= 1'b0;
                        写入数据就绪   <= 1'b0;
                        写状态         <= 写_完成;
                    end
                end

                // ---- 完成：等待从机的写响应 ----
                写_完成: begin
                    if (主机_写响应有效) begin
                        写完成 <= 1'b1;
                        写状态 <= 写_空闲;
                    end
                end
            endcase
        end
    end

endmodule
