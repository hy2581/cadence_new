// ============================================================
// FlashAttention 加速器 — 顶层模块
// 集成子模块：AXI4-Lite从机、DMA引擎、分块控制器、
//             缓冲系统、计算核心
// ============================================================

module 闪存注意力_顶层 (
    input  logic                    时钟,
    input  logic                    复位_低有效,

    // --- AXI4-Lite 从机接口（控制通道） ---
    // 写地址通道
    input  logic [AXIL地址位宽-1:0]     从机_写地址,
    input  logic                        从机_写地址有效,
    output logic                        从机_写地址就绪,
    // 写数据通道
    input  logic [AXIL数据位宽-1:0]     从机_写数据,
    input  logic [AXIL数据位宽/8-1:0]   从机_写选通,
    input  logic                        从机_写数据有效,
    output logic                        从机_写数据就绪,
    // 写响应通道
    output logic [1:0]                  从机_写响应,
    output logic                        从机_写响应有效,
    input  logic                        从机_写响应就绪,
    // 读地址通道
    input  logic [AXIL地址位宽-1:0]     从机_读地址,
    input  logic                        从机_读地址有效,
    output logic                        从机_读地址就绪,
    // 读数据通道
    output logic [AXIL数据位宽-1:0]     从机_读数据,
    output logic [1:0]                  从机_读响应,
    output logic                        从机_读数据有效,
    input  logic                        从机_读数据就绪,

    // --- AXI4 主机接口（数据通道） ---
    // 写地址通道
    output logic [AXI_ID位宽-1:0]       主机_写地址ID,
    output logic [AXI地址位宽-1:0]      主机_写地址,
    output logic [7:0]                  主机_写突发长度,
    output logic [2:0]                  主机_写突发大小,
    output logic [1:0]                  主机_写突发类型,
    output logic                        主机_写地址有效,
    input  logic                        主机_写地址就绪,
    // 写数据通道
    output logic [AXI数据位宽-1:0]      主机_写数据,
    output logic [AXI写选通位宽-1:0]    主机_写选通,
    output logic                        主机_写最后一拍,
    output logic                        主机_写数据有效,
    input  logic                        主机_写数据就绪,
    // 写响应通道
    input  logic [AXI_ID位宽-1:0]       主机_写响应ID,
    input  logic [1:0]                  主机_写响应,
    input  logic                        主机_写响应有效,
    output logic                        主机_写响应就绪,
    // 读地址通道
    output logic [AXI_ID位宽-1:0]       主机_读地址ID,
    output logic [AXI地址位宽-1:0]      主机_读地址,
    output logic [7:0]                  主机_读突发长度,
    output logic [2:0]                  主机_读突发大小,
    output logic [1:0]                  主机_读突发类型,
    output logic                        主机_读地址有效,
    input  logic                        主机_读地址就绪,
    // 读数据通道
    input  logic [AXI_ID位宽-1:0]       主机_读数据ID,
    input  logic [AXI数据位宽-1:0]      主机_读数据,
    input  logic [1:0]                  主机_读响应,
    input  logic                        主机_读最后一拍,
    input  logic                        主机_读数据有效,
    output logic                        主机_读数据就绪,

    // 中断输出
    output logic                        中断
);

    // ========== 寄存器文件信号 ==========
    logic        寄存器_启动, 寄存器_软复位, 寄存器_中断使能, 寄存器_因果掩码使能;
    logic [63:0] 寄存器_Q基地址, 寄存器_K基地址, 寄存器_V基地址, 寄存器_O基地址;
    logic [31:0] 寄存器_行步长;
    logic signed [15:0] 寄存器_负大值, 寄存器_缩放因子;
    logic        状态_忙碌, 状态_完成, 状态_错误;
    logic [31:0] 周期计数;
    logic        完成清除;

    AXI4_Lite从机 #(.地址位宽(AXIL地址位宽), .数据位宽(AXIL数据位宽))
    实例_AXIL从机 (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .从机_写地址(从机_写地址), .从机_写地址有效(从机_写地址有效), .从机_写地址就绪(从机_写地址就绪),
        .从机_写数据(从机_写数据), .从机_写选通(从机_写选通),
        .从机_写数据有效(从机_写数据有效), .从机_写数据就绪(从机_写数据就绪),
        .从机_写响应(从机_写响应), .从机_写响应有效(从机_写响应有效), .从机_写响应就绪(从机_写响应就绪),
        .从机_读地址(从机_读地址), .从机_读地址有效(从机_读地址有效), .从机_读地址就绪(从机_读地址就绪),
        .从机_读数据(从机_读数据), .从机_读响应(从机_读响应),
        .从机_读数据有效(从机_读数据有效), .从机_读数据就绪(从机_读数据就绪),
        .寄存器_启动(寄存器_启动), .寄存器_软复位(寄存器_软复位), .寄存器_中断使能(寄存器_中断使能),
        .寄存器_因果掩码使能(寄存器_因果掩码使能),
        .寄存器_Q基地址(寄存器_Q基地址), .寄存器_K基地址(寄存器_K基地址),
        .寄存器_V基地址(寄存器_V基地址), .寄存器_O基地址(寄存器_O基地址),
        .寄存器_行步长(寄存器_行步长),
        .寄存器_负大值(寄存器_负大值), .寄存器_缩放因子(寄存器_缩放因子),
        .状态_忙碌(状态_忙碌), .状态_完成(状态_完成), .状态_错误(状态_错误),
        .周期计数(周期计数), .完成清除(完成清除), .中断(中断)
    );

    // ========== DMA / 分块控制器 / 缓冲信号 ==========
    logic       控制器_DMA读请求, 控制器_DMA读完成;
    logic [AXI地址位宽-1:0] 控制器_DMA读地址;
    logic [15:0] 控制器_DMA读长度;
    logic [1:0]  控制器_DMA读目标;           // 0=Q, 1=K, 2=V
    logic       控制器_DMA写请求, 控制器_DMA写完成;
    logic [AXI地址位宽-1:0] 控制器_DMA写地址;
    logic [15:0] 控制器_DMA写长度;
    logic       控制器_计算启动, 控制器_首个KV分块, 控制器_末个KV分块, 控制器_计算完成;
    logic [$clog2(序列长度)-1:0] 控制器_Q分块索引, 控制器_KV分块索引;
    logic       控制器_KV缓冲选择;           // 乒乓缓冲选择
    logic       控制器_全部完成, 控制器_忙碌;
    logic       控制器_O回写启动, 控制器_O回写完成;

    分块控制器 #(
        .序列长度(序列长度), .头维度(头维度), .Q分块行数(Q分块行数), .KV分块行数(KV分块行数),
        .AXI地址位宽(AXI地址位宽), .数据位宽(数据位宽)
    ) 实例_分块控制器 (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .启动(寄存器_启动), .全部完成(控制器_全部完成), .忙碌(控制器_忙碌),
        .Q基地址(寄存器_Q基地址), .K基地址(寄存器_K基地址),
        .V基地址(寄存器_V基地址), .O基地址(寄存器_O基地址),
        .行步长(寄存器_行步长),
        .DMA读请求(控制器_DMA读请求), .DMA读地址(控制器_DMA读地址),
        .DMA读长度_字节(控制器_DMA读长度), .DMA读目标(控制器_DMA读目标),
        .DMA读完成(控制器_DMA读完成),
        .DMA写请求(控制器_DMA写请求), .DMA写地址(控制器_DMA写地址),
        .DMA写长度_字节(控制器_DMA写长度), .DMA写完成(控制器_DMA写完成),
        .计算启动(控制器_计算启动), .首个KV分块(控制器_首个KV分块),
        .末个KV分块(控制器_末个KV分块), .计算完成(控制器_计算完成),
        .Q分块索引(控制器_Q分块索引), .KV分块索引(控制器_KV分块索引),
        .KV缓冲选择(控制器_KV缓冲选择),
        .O回写启动(控制器_O回写启动), .O回写完成(控制器_O回写完成)
    );

    // ========== 缓冲接口信号 ==========
    logic       缓冲_Q写使能, 缓冲_K写使能, 缓冲_V写使能;
    logic [$clog2(Q分块行数*头维度)-1:0] 缓冲_Q写地址;
    logic [$clog2(KV分块行数*头维度)-1:0] 缓冲_K写地址, 缓冲_V写地址;
    logic [AXI数据位宽-1:0] 缓冲_Q写数据, 缓冲_K写数据, 缓冲_V写数据;
    logic       缓冲_O读使能;
    logic [$clog2(Q分块行数)-1:0] 缓冲_O读行号;
    logic [$clog2(头维度/(AXI数据位宽/数据位宽))-1:0] 缓冲_O读列组;
    logic [AXI数据位宽-1:0] 缓冲_O读数据;

    DMA引擎 #(
        .AXI地址位宽(AXI地址位宽), .AXI数据位宽(AXI数据位宽),
        .AXI_ID位宽(AXI_ID位宽),
        .Q分块行数(Q分块行数), .KV分块行数(KV分块行数), .头维度(头维度), .数据位宽(数据位宽)
    ) 实例_DMA (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .主机_写地址ID(主机_写地址ID), .主机_写地址(主机_写地址), .主机_写突发长度(主机_写突发长度),
        .主机_写突发大小(主机_写突发大小), .主机_写突发类型(主机_写突发类型),
        .主机_写地址有效(主机_写地址有效), .主机_写地址就绪(主机_写地址就绪),
        .主机_写数据(主机_写数据), .主机_写选通(主机_写选通),
        .主机_写最后一拍(主机_写最后一拍), .主机_写数据有效(主机_写数据有效), .主机_写数据就绪(主机_写数据就绪),
        .主机_写响应ID(主机_写响应ID), .主机_写响应(主机_写响应),
        .主机_写响应有效(主机_写响应有效), .主机_写响应就绪(主机_写响应就绪),
        .主机_读地址ID(主机_读地址ID), .主机_读地址(主机_读地址), .主机_读突发长度(主机_读突发长度),
        .主机_读突发大小(主机_读突发大小), .主机_读突发类型(主机_读突发类型),
        .主机_读地址有效(主机_读地址有效), .主机_读地址就绪(主机_读地址就绪),
        .主机_读数据ID(主机_读数据ID), .主机_读数据(主机_读数据), .主机_读响应(主机_读响应),
        .主机_读最后一拍(主机_读最后一拍), .主机_读数据有效(主机_读数据有效), .主机_读数据就绪(主机_读数据就绪),
        .DMA读请求(控制器_DMA读请求), .DMA读地址(控制器_DMA读地址),
        .DMA读长度_字节(控制器_DMA读长度), .DMA读目标(控制器_DMA读目标),
        .DMA读完成(控制器_DMA读完成),
        .DMA写请求(控制器_DMA写请求), .DMA写地址(控制器_DMA写地址),
        .DMA写长度_字节(控制器_DMA写长度), .DMA写完成(控制器_DMA写完成),
        .缓冲_Q写使能(缓冲_Q写使能), .缓冲_Q写地址(缓冲_Q写地址), .缓冲_Q写数据(缓冲_Q写数据),
        .缓冲_K写使能(缓冲_K写使能), .缓冲_K写地址(缓冲_K写地址), .缓冲_K写数据(缓冲_K写数据),
        .缓冲_V写使能(缓冲_V写使能), .缓冲_V写地址(缓冲_V写地址), .缓冲_V写数据(缓冲_V写数据),
        .缓冲_O读使能(缓冲_O读使能), .缓冲_O读行号(缓冲_O读行号),
        .缓冲_O读列组(缓冲_O读列组), .缓冲_O读数据(缓冲_O读数据),
        .KV缓冲选择(控制器_KV缓冲选择)
    );

    // ========== 计算核心与缓冲的读接口信号 ==========
    logic       计算_Q读使能, 计算_K读使能, 计算_V读使能;
    logic [$clog2(头维度/并行乘累加数)-1:0] 计算_Q步进, 计算_K步进, 计算_V步进;
    logic signed [数据位宽-1:0] 计算_Q数据 [Q分块行数-1:0][并行乘累加数-1:0];
    logic signed [数据位宽-1:0] 计算_K数据 [KV分块行数-1:0][并行乘累加数-1:0];
    logic signed [数据位宽-1:0] 计算_V数据 [KV分块行数-1:0][并行乘累加数-1:0];
    logic signed [数据位宽-1:0] 计算_O分块 [Q分块行数-1:0][头维度-1:0];
    logic       计算_O有效;

    缓冲系统 #(
        .Q分块行数(Q分块行数), .KV分块行数(KV分块行数), .头维度(头维度),
        .数据位宽(数据位宽), .并行乘累加数(并行乘累加数), .AXI数据位宽(AXI数据位宽)
    ) 实例_缓冲系统 (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .Q写使能(缓冲_Q写使能), .Q写地址(缓冲_Q写地址), .Q写数据(缓冲_Q写数据),
        .K写使能(缓冲_K写使能), .K写地址(缓冲_K写地址), .K写数据(缓冲_K写数据),
        .K缓冲选择(控制器_KV缓冲选择),
        .V写使能(缓冲_V写使能), .V写地址(缓冲_V写地址), .V写数据(缓冲_V写数据),
        .V缓冲选择(控制器_KV缓冲选择),
        .Q读使能(计算_Q读使能), .Q读步进(计算_Q步进), .Q读数据(计算_Q数据),
        .K读使能(计算_K读使能), .K读步进(计算_K步进),
        .K读缓冲选择(~控制器_KV缓冲选择), .K读数据(计算_K数据),
        .V读使能(计算_V读使能), .V读步进(计算_V步进),
        .V读缓冲选择(~控制器_KV缓冲选择), .V读数据(计算_V数据),
        .O写使能(计算_O有效), .O写数据(计算_O分块),
        .O读使能(缓冲_O读使能), .O读行号(缓冲_O读行号),
        .O读列组(缓冲_O读列组), .O读数据(缓冲_O读数据)
    );

    计算核心 #(
        .序列长度(序列长度), .头维度(头维度), .Q分块行数(Q分块行数), .KV分块行数(KV分块行数),
        .数据位宽(数据位宽), .累加器位宽(累加器位宽),
        .指数输出位宽(24), .小数位数(16), .并行乘累加数(并行乘累加数)
    ) 实例_计算核心 (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .启动(控制器_计算启动), .首个KV分块(控制器_首个KV分块),
        .末个KV分块(控制器_末个KV分块),
        .完成(控制器_计算完成), .忙碌(),
        .Q分块索引(控制器_Q分块索引), .KV分块索引(控制器_KV分块索引),
        .因果掩码使能(寄存器_因果掩码使能), .缩放因子(寄存器_缩放因子), .负大值(寄存器_负大值),
        .Q读使能(计算_Q读使能), .Q读步进(计算_Q步进), .Q数据(计算_Q数据),
        .K读使能(计算_K读使能), .K读步进(计算_K步进), .K数据(计算_K数据),
        .V读使能(计算_V读使能), .V读步进(计算_V步进), .V数据(计算_V数据),
        .O分块(计算_O分块), .O有效(计算_O有效)
    );

    // ========== 周期计数器 ==========
    logic [31:0] 周期计数器;
    assign 周期计数 = 周期计数器;

    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效)
            周期计数器 <= '0;
        else if (寄存器_启动)
            周期计数器 <= '0;            // 启动时清零
        else if (控制器_忙碌)
            周期计数器 <= 周期计数器 + 1; // 运行中递增
    end

    // ========== 状态输出 ==========
    assign 状态_忙碌  = 控制器_忙碌;
    assign 状态_完成  = 控制器_全部完成;
    assign 状态_错误  = 1'b0;  // 暂未实现错误检测

    // O回写完成信号连接
    assign 控制器_O回写完成 = 控制器_DMA写完成;

endmodule
