// ============================================================
// 指数近似单元 — 基于查找表的直接实现
// 输入：有符号定点数 Q(输入位宽-输入小数位).输入小数位
// 输出：无符号定点数 Q(输出位宽-输出小数位).输出小数位
// 范围：exp(x)，x ∈ [-16, +4]
// 方法：3级流水线查找表（单周期查表 + 流水线寄存器提升时序）
// ============================================================
module 指数近似单元 #(
    parameter 输入位宽     = 40,
    parameter 输入小数位   = 8,
    parameter 输出位宽     = 24,
    parameter 输出小数位   = 16
)(
    input  logic                        时钟,
    input  logic                        复位_低有效,
    input  logic                        输入有效,
    input  logic signed [输入位宽-1:0]  输入值,
    input  logic signed [15:0]          负大值,
    output logic                        输出有效,
    output logic [输出位宽-1:0]         指数输出
);

    // 查找表：1024个条目，覆盖 x 从 -16.0 到 +4.0
    // 步长 = 20.0/1024 ≈ 0.01953125
    // 索引 = (x实数 + 16.0) / 0.01953125 = (x实数 + 16.0) × 51.2
    localparam 查找表大小 = 1024;

    // ===== 第1级流水线：将输入转换为查找表索引 =====
    logic 第1级有效;
    logic [9:0] 第1级索引;
    logic 第1级_下限截断, 第1级_上限截断;

    // 组合逻辑计算索引
    reg signed [输入位宽-1:0] 加16后的值;
    reg signed [输入位宽-1:0] 索引计算值;

    always @(*) begin
        加16后的值 = 输入值 + (16 * (1 << 输入小数位));   // x + 16（定点数）
        索引计算值 = 加16后的值 / 5;                      // 近似除法得到索引
    end

    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            第1级有效     <= 0;
            第1级索引     <= 0;
            第1级_下限截断 <= 0;
            第1级_上限截断 <= 0;
        end else begin
            第1级有效 <= 输入有效;
            if (加16后的值 <= 0) begin
                // x < -16：exp值极小，截断为0
                第1级索引     <= 0;
                第1级_下限截断 <= 1;
                第1级_上限截断 <= 0;
            end else if (索引计算值 >= 查找表大小) begin
                // x > +4：exp值很大，截断为最大值
                第1级索引     <= 查找表大小 - 1;
                第1级_下限截断 <= 0;
                第1级_上限截断 <= 1;
            end else begin
                // 正常范围：使用计算出的索引
                第1级索引     <= 索引计算值[9:0];
                第1级_下限截断 <= 0;
                第1级_上限截断 <= 0;
            end
        end
    end

    // 查找表ROM实例（在第1级索引确定后查表）
    wire [输出位宽-1:0] ROM查表数据;
    指数查找表ROM 实例_查找表ROM (.地址(第1级索引), .数据(ROM查表数据));

    // ===== 第2级流水线：锁存查找表读出值 =====
    logic 第2级有效;
    logic [输出位宽-1:0] 第2级_查表值;
    logic 第2级_下限截断, 第2级_上限截断;

    wire [输出位宽-1:0] 查表读出值 = ROM查表数据;

    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            第2级有效     <= 0;
            第2级_查表值   <= 0;
            第2级_下限截断 <= 0;
            第2级_上限截断 <= 0;
        end else begin
            第2级有效     <= 第1级有效;
            第2级_查表值   <= 查表读出值;
            第2级_下限截断 <= 第1级_下限截断;
            第2级_上限截断 <= 第1级_上限截断;
        end
    end

    // ===== 第3级流水线：输出结果（含截断处理） =====
    logic 第3级有效;
    logic [输出位宽-1:0] 第3级_结果;

    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            第3级有效 <= 0;
            第3级_结果 <= 0;
        end else begin
            第3级有效 <= 第2级有效;
            if (第2级_下限截断)
                第3级_结果 <= 0;                    // x太小，exp(x) ≈ 0
            else if (第2级_上限截断)
                第3级_结果 <= {输出位宽{1'b1}};     // x太大，exp(x)饱和到最大值
            else
                第3级_结果 <= 第2级_查表值;          // 正常值
        end
    end

    assign 输出有效 = 第3级有效;
    assign 指数输出 = 第3级_结果;

endmodule
