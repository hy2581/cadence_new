// ============================================================
// AXI4-Lite 从机接口 + 寄存器文件
// 实现FlashAttention加速器的控制/状态寄存器空间
// 软件通过此接口配置加速器参数并启动计算
// ============================================================
module AXI4_Lite从机 #(
    parameter 地址位宽 = 8,
    parameter 数据位宽 = 32
)(
    input  logic                    时钟,
    input  logic                    复位_低有效,

    // AXI4-Lite 写地址通道
    input  logic [地址位宽-1:0]     从机_写地址,
    input  logic                    从机_写地址有效,
    output logic                    从机_写地址就绪,

    // AXI4-Lite 写数据通道
    input  logic [数据位宽-1:0]     从机_写数据,
    input  logic [数据位宽/8-1:0]   从机_写选通,
    input  logic                    从机_写数据有效,
    output logic                    从机_写数据就绪,

    // AXI4-Lite 写响应通道
    output logic [1:0]              从机_写响应,
    output logic                    从机_写响应有效,
    input  logic                    从机_写响应就绪,

    // AXI4-Lite 读地址通道
    input  logic [地址位宽-1:0]     从机_读地址,
    input  logic                    从机_读地址有效,
    output logic                    从机_读地址就绪,

    // AXI4-Lite 读数据通道
    output logic [数据位宽-1:0]     从机_读数据,
    output logic [1:0]              从机_读响应,
    output logic                    从机_读数据有效,
    input  logic                    从机_读数据就绪,

    // 寄存器输出（连接到数据通路）
    output logic                    寄存器_启动,        // 脉冲信号，写1启动计算
    output logic                    寄存器_软复位,      // 脉冲信号，写1软复位
    output logic                    寄存器_中断使能,
    output logic                    寄存器_因果掩码使能,
    output logic [63:0]             寄存器_Q基地址,
    output logic [63:0]             寄存器_K基地址,
    output logic [63:0]             寄存器_V基地址,
    output logic [63:0]             寄存器_O基地址,
    output logic [31:0]             寄存器_行步长,
    output logic signed [15:0]      寄存器_负大值,
    output logic signed [15:0]      寄存器_缩放因子,

    // 状态输入（来自数据通路）
    input  logic                    状态_忙碌,
    input  logic                    状态_完成,
    input  logic                    状态_错误,
    input  logic [31:0]             周期计数,

    // 完成清除（写1清除完成标志）
    output logic                    完成清除,

    // 中断输出
    output logic                    中断
);

    // ========== 内部寄存器 ==========
    logic [31:0] 内部_控制寄存器;
    logic [31:0] 内部_配置寄存器;
    logic [31:0] 内部_Q基地址低, 内部_Q基地址高;
    logic [31:0] 内部_K基地址低, 内部_K基地址高;
    logic [31:0] 内部_V基地址低, 内部_V基地址高;
    logic [31:0] 内部_O基地址低, 内部_O基地址高;
    logic [31:0] 内部_行步长;
    logic [31:0] 内部_负大值;
    logic [31:0] 内部_缩放因子;
    logic        完成粘滞位;        // 完成标志（粘滞，需要软件写1清除）

    // 写通道状态
    logic 写地址就绪_寄存器, 写数据就绪_寄存器;
    logic [地址位宽-1:0] 写地址_锁存;
    logic 写使能;

    // 读通道状态
    logic 读地址就绪_寄存器;
    logic [数据位宽-1:0] 读数据_寄存器;
    logic 读有效_寄存器;

    assign 从机_写地址就绪 = 写地址就绪_寄存器;
    assign 从机_写数据就绪 = 写数据就绪_寄存器;
    assign 从机_写响应     = 2'b00;      // 始终返回OKAY
    assign 从机_读地址就绪 = 读地址就绪_寄存器;
    assign 从机_读数据     = 读数据_寄存器;
    assign 从机_读响应     = 2'b00;      // 始终返回OKAY
    assign 从机_读数据有效 = 读有效_寄存器;

    // ========== 写逻辑 ==========
    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            写地址就绪_寄存器  <= 1'b1;
            写数据就绪_寄存器  <= 1'b1;
            从机_写响应有效    <= 1'b0;
            写使能             <= 1'b0;
            写地址_锁存        <= '0;
            内部_控制寄存器    <= '0;
            内部_配置寄存器    <= '0;
            内部_Q基地址低     <= '0; 内部_Q基地址高 <= '0;
            内部_K基地址低     <= '0; 内部_K基地址高 <= '0;
            内部_V基地址低     <= '0; 内部_V基地址高 <= '0;
            内部_O基地址低     <= '0; 内部_O基地址高 <= '0;
            内部_行步长        <= 32'd128;      // 默认值 d×2 = 128
            内部_负大值        <= 32'hFFFF8000;  // 默认 -128.0
            内部_缩放因子      <= 32'h00000020;  // 默认 1/8
            完成粘滞位         <= 1'b0;
            寄存器_启动        <= 1'b0;
            寄存器_软复位      <= 1'b0;
            完成清除           <= 1'b0;
        end else begin
            寄存器_启动   <= 1'b0;   // 脉冲信号，每周期自动清零
            寄存器_软复位 <= 1'b0;
            完成清除      <= 1'b0;

            // 写响应握手：主机确认收到响应后清除
            if (从机_写响应有效 && 从机_写响应就绪)
                从机_写响应有效 <= 1'b0;

            // 写地址 + 写数据同时有效时执行写操作
            if (从机_写地址有效 && 从机_写地址就绪 && 从机_写数据有效 && 从机_写数据就绪) begin
                从机_写响应有效 <= 1'b1;    // 发送写响应
                case (从机_写地址)
                    8'h00: begin  // 控制寄存器
                        内部_控制寄存器 <= 从机_写数据;
                        if (从机_写数据[0]) 寄存器_启动   <= 1'b1;  // 位0：启动
                        if (从机_写数据[1]) 寄存器_软复位 <= 1'b1;  // 位1：软复位
                    end
                    8'h04: begin  // 状态寄存器（写1清除完成位）
                        if (从机_写数据[1]) begin
                            完成粘滞位 <= 1'b0;
                            完成清除   <= 1'b1;
                        end
                    end
                    8'h08: 内部_配置寄存器 <= 从机_写数据;    // 配置寄存器
                    8'h14: 内部_Q基地址低  <= 从机_写数据;    // Q基地址低32位
                    8'h18: 内部_Q基地址高  <= 从机_写数据;    // Q基地址高32位
                    8'h1C: 内部_K基地址低  <= 从机_写数据;    // K基地址低32位
                    8'h20: 内部_K基地址高  <= 从机_写数据;    // K基地址高32位
                    8'h24: 内部_V基地址低  <= 从机_写数据;    // V基地址低32位
                    8'h28: 内部_V基地址高  <= 从机_写数据;    // V基地址高32位
                    8'h2C: 内部_O基地址低  <= 从机_写数据;    // O基地址低32位
                    8'h30: 内部_O基地址高  <= 从机_写数据;    // O基地址高32位
                    8'h34: 内部_行步长     <= 从机_写数据;    // 行步长
                    8'h38: 内部_负大值     <= 从机_写数据;    // 负大值
                    8'h3C: 内部_缩放因子   <= 从机_写数据;    // 缩放因子
                    default: ;
                endcase
            end

            // 完成粘滞位：计算完成时置1，直到软件写1清除
            if (状态_完成)
                完成粘滞位 <= 1'b1;
        end
    end

    // ========== 读逻辑 ==========
    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            读地址就绪_寄存器 <= 1'b1;
            读有效_寄存器     <= 1'b0;
            读数据_寄存器     <= '0;
        end else begin
            // 主机确认收到读数据后清除有效标志
            if (读有效_寄存器 && 从机_读数据就绪)
                读有效_寄存器 <= 1'b0;

            // 收到读地址后返回对应寄存器的值
            if (从机_读地址有效 && 从机_读地址就绪) begin
                读有效_寄存器 <= 1'b1;
                case (从机_读地址)
                    8'h00: 读数据_寄存器 <= 内部_控制寄存器;
                    8'h04: 读数据_寄存器 <= {29'd0, 状态_错误, 完成粘滞位, 状态_忙碌};
                    8'h08: 读数据_寄存器 <= 内部_配置寄存器;
                    8'h14: 读数据_寄存器 <= 内部_Q基地址低;
                    8'h18: 读数据_寄存器 <= 内部_Q基地址高;
                    8'h1C: 读数据_寄存器 <= 内部_K基地址低;
                    8'h20: 读数据_寄存器 <= 内部_K基地址高;
                    8'h24: 读数据_寄存器 <= 内部_V基地址低;
                    8'h28: 读数据_寄存器 <= 内部_V基地址高;
                    8'h2C: 读数据_寄存器 <= 内部_O基地址低;
                    8'h30: 读数据_寄存器 <= 内部_O基地址高;
                    8'h34: 读数据_寄存器 <= 内部_行步长;
                    8'h38: 读数据_寄存器 <= 内部_负大值;
                    8'h3C: 读数据_寄存器 <= 内部_缩放因子;
                    8'h40: 读数据_寄存器 <= 周期计数;
                    default: 读数据_寄存器 <= 32'hDEADBEEF;  // 无效地址返回特征值
                endcase
            end
        end
    end

    // ========== 输出赋值 ==========
    assign 寄存器_中断使能     = 内部_控制寄存器[2];            // 控制寄存器位2
    assign 寄存器_因果掩码使能 = 内部_配置寄存器[0];            // 配置寄存器位0
    assign 寄存器_Q基地址      = {内部_Q基地址高, 内部_Q基地址低};  // 拼接64位地址
    assign 寄存器_K基地址      = {内部_K基地址高, 内部_K基地址低};
    assign 寄存器_V基地址      = {内部_V基地址高, 内部_V基地址低};
    assign 寄存器_O基地址      = {内部_O基地址高, 内部_O基地址低};
    assign 寄存器_行步长       = 内部_行步长;
    assign 寄存器_负大值       = 内部_负大值[15:0];             // 取低16位
    assign 寄存器_缩放因子     = 内部_缩放因子[15:0];

    // ========== 中断逻辑 ==========
    // 当中断使能且计算完成时，输出中断
    assign 中断 = 寄存器_中断使能 & 完成粘滞位;

endmodule
