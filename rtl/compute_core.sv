// ============================================================
// 计算核心
// 编排整个计算流水线：点积 → 因果掩码 → 在线Softmax → 输出累加
// 处理一对 (Q分块, KV分块) 的注意力计算
// ============================================================
module 计算核心 #(
    parameter 序列长度     = 256,
    parameter 头维度       = 64,
    parameter Q分块行数    = 4,
    parameter KV分块行数   = 16,
    parameter 数据位宽     = 16,
    parameter 累加器位宽   = 40,
    parameter 指数输出位宽 = 24,
    parameter 小数位数     = 16,
    parameter 并行乘累加数 = 8
)(
    input  logic                          时钟,
    input  logic                          复位_低有效,

    // 控制信号
    input  logic                          启动,
    input  logic                          首个KV分块,    // 是否为当前Q分块的第一个KV分块
    input  logic                          末个KV分块,    // 是否为当前Q分块的最后一个KV分块
    output logic                          完成,
    output logic                          忙碌,

    // 分块索引（用于因果掩码计算）
    input  logic [$clog2(序列长度)-1:0]   Q分块索引,
    input  logic [$clog2(序列长度)-1:0]   KV分块索引,

    // 配置参数
    input  logic                          因果掩码使能,
    input  logic signed [数据位宽-1:0]    缩放因子,      // 注意力分数缩放 1/√d
    input  logic signed [15:0]            负大值,        // 掩码位置填充的负大数

    // Q分块缓冲读接口（每周期读 Q分块行数 × 并行乘累加数 个元素）
    output logic                          Q读使能,
    output logic [$clog2(头维度/并行乘累加数)-1:0] Q读步进,
    input  logic signed [数据位宽-1:0]    Q数据 [Q分块行数-1:0][并行乘累加数-1:0],

    // K分块缓冲读接口
    output logic                          K读使能,
    output logic [$clog2(头维度/并行乘累加数)-1:0] K读步进,
    input  logic signed [数据位宽-1:0]    K数据 [KV分块行数-1:0][并行乘累加数-1:0],

    // V分块缓冲读接口
    output logic                          V读使能,
    output logic [$clog2(头维度/并行乘累加数)-1:0] V读步进,
    input  logic signed [数据位宽-1:0]    V数据 [KV分块行数-1:0][并行乘累加数-1:0],

    // 输出：O分块（Q分块行数 × 头维度），最后一个KV分块时有效
    output logic signed [数据位宽-1:0]    O分块 [Q分块行数-1:0][头维度-1:0],
    output logic                          O有效
);

    localparam 索引位宽 = $clog2(序列长度);
    localparam 步数     = 头维度 / 并行乘累加数;    // 64/8 = 8步

    // ===== 主控状态机 =====
    typedef enum logic [2:0] {
        空闲,          // 等待启动
        点积计算,      // 计算 S = Q · K^T
        掩码处理,      // 应用因果掩码
        软最大值计算,  // 在线Softmax计算
        累加计算,      // 输出累加 O += P · V
        处理完成       // 本轮计算完成
    } 状态类型;

    状态类型 当前状态;

    // ===== 点积模块信号 =====
    logic 点积_启动, 点积_完成, 点积_忙碌;
    logic signed [累加器位宽-1:0] 点积_分数矩阵 [Q分块行数-1:0][KV分块行数-1:0];
    logic 点积_分数有效;
    logic 点积_数据有效;
    logic [$clog2(步数):0] 点积_步进;

    点积阵列 #(
        .Q分块行数(Q分块行数), .KV分块行数(KV分块行数), .头维度(头维度),
        .数据位宽(数据位宽), .累加器位宽(累加器位宽), .并行乘累加数(并行乘累加数)
    ) 实例_点积 (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .启动(点积_启动), .完成(点积_完成), .忙碌(点积_忙碌),
        .Q数据(Q数据), .K数据(K数据), .数据有效(点积_数据有效),
        .缩放因子(缩放因子),
        .分数矩阵(点积_分数矩阵), .分数有效(点积_分数有效)
    );

    // ===== 掩码后的分数矩阵 =====
    logic signed [累加器位宽-1:0] 掩码后分数 [Q分块行数-1:0][KV分块行数-1:0];

    // ===== 在线Softmax模块信号 =====
    logic Softmax_启动, Softmax_完成, Softmax_忙碌;
    logic signed [累加器位宽-1:0] 旧最大值 [Q分块行数-1:0];   // 上一轮的行最大值
    logic [累加器位宽-1:0]        旧分母和 [Q分块行数-1:0];   // 上一轮的行分母和
    logic signed [累加器位宽-1:0] 新最大值 [Q分块行数-1:0];   // 本轮更新后的行最大值
    logic [累加器位宽-1:0]        新分母和 [Q分块行数-1:0];   // 本轮更新后的行分母和
    logic [指数输出位宽-1:0]      概率矩阵 [Q分块行数-1:0][KV分块行数-1:0];  // exp(score - max)
    logic [累加器位宽-1:0]        缩放修正 [Q分块行数-1:0];   // 旧O的缩放因子
    logic                         Softmax_结果有效;

    在线Softmax单元 #(
        .Q分块行数(Q分块行数), .KV分块行数(KV分块行数),
        .分数位宽(累加器位宽), .指数输出位宽(指数输出位宽), .小数位数(小数位数)
    ) 实例_Softmax (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .启动(Softmax_启动), .首个分块(首个KV分块), .完成(Softmax_完成), .忙碌(Softmax_忙碌),
        .分数矩阵(掩码后分数), .负大值(负大值),
        .旧最大值(旧最大值), .旧分母和(旧分母和),
        .新最大值(新最大值), .新分母和(新分母和),
        .概率矩阵(概率矩阵), .缩放修正(缩放修正), .结果有效(Softmax_结果有效)
    );

    // ===== 输出累加器信号 =====
    logic 累加_启动, 累加_完成, 累加_忙碌;
    logic 累加_V有效;
    logic [$clog2(步数):0] 累加_V步进;

    输出累加器 #(
        .Q分块行数(Q分块行数), .KV分块行数(KV分块行数), .头维度(头维度),
        .数据位宽(数据位宽), .累加器位宽(累加器位宽),
        .指数输出位宽(指数输出位宽), .小数位数(小数位数), .并行列数(并行乘累加数)
    ) 实例_输出累加器 (
        .时钟(时钟), .复位_低有效(复位_低有效),
        .启动(累加_启动), .首个分块(首个KV分块), .末个分块(末个KV分块),
        .完成(累加_完成), .忙碌(累加_忙碌),
        .概率矩阵(概率矩阵),
        .V数据(V数据), .V有效(累加_V有效),
        .缩放修正(缩放修正), .分母和(新分母和),
        .O输出(O分块), .O有效(O有效)
    );

    // ===== Softmax状态持久化（跨KV分块保持） =====
    // 在处理同一Q分块的多个KV分块时，需要保持最大值和分母和
    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            for (int 行 = 0; 行 < Q分块行数; 行++) begin
                旧最大值[行] <= {累加器位宽{1'b1}};  // 初始化为负无穷
                旧分母和[行] <= '0;                   // 初始化为0
            end
        end else if (Softmax_结果有效) begin
            // Softmax完成后，将新值保存为旧值，供下一轮使用
            for (int 行 = 0; 行 < Q分块行数; 行++) begin
                旧最大值[行] <= 新最大值[行];
                旧分母和[行] <= 新分母和[行];
            end
        end else if (当前状态 == 空闲 && 启动 && 首个KV分块) begin
            // 新的Q分块开始，重置状态
            for (int 行 = 0; 行 < Q分块行数; 行++) begin
                旧最大值[行] <= {累加器位宽{1'b1}};
                旧分母和[行] <= '0;
            end
        end
    end

    // ===== 主控状态机 =====
    always_ff @(posedge 时钟 or negedge 复位_低有效) begin
        if (!复位_低有效) begin
            当前状态     <= 空闲;
            完成         <= 1'b0;
            忙碌         <= 1'b0;
            点积_启动    <= 1'b0;
            Softmax_启动 <= 1'b0;
            累加_启动    <= 1'b0;
            点积_步进    <= '0;
            点积_数据有效 <= 1'b0;
            Q读使能      <= 1'b0;
            K读使能      <= 1'b0;
            V读使能      <= 1'b0;
            累加_V有效   <= 1'b0;
            累加_V步进   <= '0;
        end else begin
            完成          <= 1'b0;
            点积_启动     <= 1'b0;
            Softmax_启动  <= 1'b0;
            累加_启动     <= 1'b0;
            点积_数据有效 <= 1'b0;
            Q读使能       <= 1'b0;
            K读使能       <= 1'b0;
            V读使能       <= 1'b0;
            累加_V有效    <= 1'b0;

            case (当前状态)
                // ---- 空闲：等待启动信号 ----
                空闲: begin
                    if (启动) begin
                        当前状态  <= 点积计算;
                        忙碌      <= 1'b1;
                        点积_启动 <= 1'b1;
                        点积_步进 <= '0;
                    end
                end

                // ---- 点积计算：流式输入Q和K数据到点积单元 ----
                // 每周期送入一步(8个元素)，共8步完成d=64维的点积
                点积计算: begin
                    if (!点积_完成 && 点积_忙碌) begin
                        Q读使能       <= 1'b1;
                        K读使能       <= 1'b1;
                        Q读步进       <= 点积_步进[$clog2(步数)-1:0];
                        K读步进       <= 点积_步进[$clog2(步数)-1:0];
                        点积_数据有效 <= 1'b1;
                        点积_步进     <= 点积_步进 + 1;
                    end
                    if (点积_完成) begin
                        当前状态 <= 掩码处理;
                    end
                end

                // ---- 掩码处理：对分数矩阵应用因果掩码 ----
                // 当 列索引 > 行索引 时，用负大值替换（防止看到未来信息）
                掩码处理: begin
                    for (int 行 = 0; 行 < Q分块行数; 行++) begin
                        for (int 列 = 0; 列 < KV分块行数; 列++) begin
                            logic 掩码位;
                            logic [索引位宽-1:0] 绝对行号, 绝对列号;
                            绝对行号 = Q分块索引 * Q分块行数 + 索引位宽'(行);
                            绝对列号 = KV分块索引 * KV分块行数 + 索引位宽'(列);
                            掩码位 = 因果掩码使能 & (绝对列号 > 绝对行号);
                            if (掩码位)
                                // 被掩码的位置填充负大值（使exp后趋近于0）
                                掩码后分数[行][列] <= {{(累加器位宽-16){负大值[15]}}, 负大值};
                            else
                                掩码后分数[行][列] <= 点积_分数矩阵[行][列];
                        end
                    end
                    当前状态     <= 软最大值计算;
                    Softmax_启动 <= 1'b1;
                end

                // ---- Softmax计算：在线Softmax处理 ----
                软最大值计算: begin
                    if (Softmax_完成) begin
                        当前状态  <= 累加计算;
                        累加_启动 <= 1'b1;
                        累加_V步进 <= '0;
                    end
                end

                // ---- 累加计算：O += P · V ----
                // 流式输入V数据到输出累加器
                累加计算: begin
                    if (累加_忙碌 && !累加_完成) begin
                        V读使能    <= 1'b1;
                        V读步进    <= 累加_V步进[$clog2(步数)-1:0];
                        累加_V有效 <= 1'b1;
                        累加_V步进 <= 累加_V步进 + 1;
                    end
                    if (累加_完成) begin
                        当前状态 <= 处理完成;
                    end
                end

                // ---- 完成：通知上层 ----
                处理完成: begin
                    完成     <= 1'b1;
                    忙碌     <= 1'b0;
                    当前状态 <= 空闲;
                end
            endcase
        end
    end

endmodule
